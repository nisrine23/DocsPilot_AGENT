def build_tag_prompt(full_text: str) -> str:
    return (
        f"Tu es un expert en équipements industriels. Analyse TOUT le texte et liste "
        f"UNIQUEMENT les repères de POMPES distinctes (ex. P-101, 304DP02, 313FP01D), "
        f"c.-à-d. le repère OFFICIEL de la pompe (champ 'Item No.' / 'Tag' / "
        f"'Repère' / 'Equipment No.').\n"
        f"RÈGLES STRICTES :\n"
        f"- N'inclus JAMAIS les numéros de plans, dessins ou croquis (champs "
        f"'Drawing', 'Plan', 'Sketch', 'Ref. Drawing', 'Plan croquis' — souvent "
        f"plusieurs codes listés ensemble séparés par des virgules comme "
        f"'313F-P-01D, 304D-D-01, 304-DE-01, 313-F-R03'). Ce ne sont PAS des pompes.\n"
        f"- N'inclus PAS le modèle/taille de la pompe (ex. 'A22 - 65 O / 1').\n"
        f"- Un même repère écrit de plusieurs façons (304DP02, 304-DP-02, DP02) "
        f"compte pour UNE SEULE pompe : ne le liste qu'une fois.\n"
        f"- N'inclus PAS les repères d'autres équipements : réservoirs (D/DS/DD/T...), "
        f"vannes (HV/FE), séparateurs, moteurs seuls, lignes de procédé.\n"
        f"- Une fiche technique (datasheet) ne décrit généralement qu'UNE SEULE "
        f"pompe : en cas de doute, ne multiplie pas les repères.\n"
        f"- Sois exhaustif, n'en oublie aucun repère réel.\n\n"
        f"Réponds strictement en JSON: {{\"tags\": [\"Repere1\", \"Repere2\"]}}.\n\n"
        f"Texte: {full_text[:40000]}"
    )


def build_extraction_prompt(tag: str, context: str, lex_body: dict) -> str:
    # Squelette JSON attendu (clés seules, sans les synonymes)
    skeleton = {
        cat: {field: {"valeur": "", "page": ""} for field in fields}
        for cat, fields in lex_body.items()
    }
    # Guide des synonymes FR + EN pour chaque champ
    synonym_guide = "\n".join(
        f"- {cat} > {field} : on peut le trouver sous les libellés {', '.join(syns)}"
        for cat, fields in lex_body.items()
        for field, syns in fields.items()
    )

    return (
        f"Tu es un ingénieur expert en spécification de pompes. "
        f"Tu dois remplir une fiche technique pour la pompe repère « {tag} » "
        f"à partir du TEXTE fourni (français OU anglais).\n\n"
        f"### TEXTE SOURCE (peut combiner plusieurs fichiers / pages)\n{context}\n\n"
        f"### CHAMPS À REMPLIR ET LEURS SYNONYMES\n"
        f"Chaque champ peut apparaître sous différents libellés, FR comme EN :\n{synonym_guide}\n\n"
        f"### MÉTHODE (obligatoire)\n"
        f"Pour CHAQUE champ du squelette :\n"
        f"1. Cherche dans le texte une mention correspondant à l'un de ses synonymes.\n"
        f"2. Recopie la valeur trouvée dans 'valeur', AVEC son unité.\n"
        f"3. Indique la source dans 'page' au format « NomFichier - Page X » "
        f"(donnée par les marqueurs [[FILE:... | PAGE:...]]).\n"
        f"4. Ne laisse 'valeur' vide QUE si l'info est réellement absente. "
        f"Jamais 'N/A' ni la liste de synonymes comme valeur.\n"
        f"5. Croise TOUS les fichiers du contexte.\n\n"
        f"### RÈGLES ANTI-CONFUSION (très important — erreurs fréquentes à éviter)\n"
        f"a) UNITÉS = NATURE DU CHAMP. Une valeur en mètres (m, m liquid) est une "
        f"HAUTEUR ou un NPSH, JAMAIS une puissance. Une valeur en kW/HP est une "
        f"PUISSANCE. Une valeur en m3/h est un DÉBIT. Une valeur en rpm/tr/min est "
        f"une VITESSE. N'attribue jamais une valeur à un champ dont l'unité ne "
        f"correspond pas. Exemple à NE PAS faire : mettre « 13.38 m » dans "
        f"Puissance_absorbee — 13.38 m est une hauteur (Max. Head), pas une puissance.\n"
        f"b) NPSH vs HAUTEUR. NPSH_disponible se remplit UNIQUEMENT avec une ligne "
        f"explicitement nommée NPSH (NPSHa, NPSHr, NPSH available/required). "
        f"Hauteur_manometrique se remplit avec Head / TDH / Rated Head / Max Head. "
        f"Ne mets jamais la valeur de NPSH dans Hauteur, ni l'inverse. S'il y a un "
        f"NPSHr (ex. « NPSHr 1.83 m »), c'est lui la valeur NPSH.\n"
        f"c) PUISSANCE ABSORBÉE vs PUISSANCE MOTEUR. 'Rated Power' / 'Absorbed power' "
        f"(puissance à l'arbre de la pompe) → Puissance_absorbee. 'Motor kW' / "
        f"'Motor rating' (puissance du moteur) → Puissance_moteur. Ce sont DEUX "
        f"champs distincts, ne mets pas la même valeur dans les deux.\n"
        f"d) VALEURS MULTIPLES (Rated / Normal / Design / Other). Si une grandeur a "
        f"plusieurs valeurs, recopie-les toutes en les étiquetant, ex. "
        f"« 24 m3/h (Normal) / 28 m3/h (Design) ». Ne mélange pas les valeurs de "
        f"deux grandeurs différentes.\n"
        f"e) NORME ≠ N° DE DOCUMENT. Le champ Norme attend une norme technique "
        f"reconnue (ex. ASME B16.5, API 610, ISO 5199, ANSI, DIN, EN...). "
        f"Ne mets JAMAIS un numéro de document, de spécification ou de projet "
        f"(ex. « Specification No. Q3709131-01-ME-SPC-00002 », « Project No. ») "
        f"dans Norme — ce ne sont pas des normes. Si aucune norme reconnue "
        f"n'apparaît, laisse Norme vide.\n"
        f"e-bis) TYPE DE POMPE ≠ MODÈLE/TAILLE. Le champ Type_de_pompe attend la "
        f"NATURE de la pompe (ex. « Horizontal, Centrifugal », « Vertical, "
        f"multicellulaire », « Submersible »), généralement au champ 'Type'. "
        f"N'y mets JAMAIS la taille/référence commerciale du modèle (champ 'Size "
        f"& Model', ex. « A22 - 65 O / 1 ») : ça, c'est le modèle, pas le type. "
        f"Si le texte donne « Type: Horizontal, Centrifugal » et « Size & Model: "
        f"A22 - 65 O / 1 », alors Type_de_pompe = « Horizontal, Centrifugal ».\n"
        f"f) TYPE D'ENTRAÎNEMENT = LIAISON MÉCANIQUE. Type_entrainement attend la "
        f"liaison pompe-moteur (ex. Direct coupled / accouplement direct, "
        f"courroie/V-belt, transmission). N'y mets PAS un mode de pilotage "
        f"électrique du moteur (VFD, DOL, ESD) : ce ne sont pas des types "
        f"d'entraînement mécanique.\n"
        f"g) TEMPÉRATURE — respecte les colonnes. Recopie la valeur Normal et la "
        f"valeur Design/Max telles qu'écrites dans LEUR colonne, sans les "
        f"confondre. N'ajoute une température issue d'une note (ex. « design "
        f"temperature is 60°C ») que si tu la distingues clairement, ex. "
        f"« 40°C (Normal) / 45°C (Max) ; 60°C (note design) ».\n"
        f"h) RESTE FIDÈLE AU TEXTE. Ne calcule rien, ne devine pas. Si une valeur "
        f"est ambiguë, recopie-la telle quelle plutôt que de l'attribuer au "
        f"mauvais champ.\n"
        f"i) VALEURS CONDITIONNELLES, PLAGES ET RENVOIS = À RECOPIER. Une valeur "
        f"présente dans le texte doit être extraite MÊME si elle est :\n"
        f"   - conditionnelle (ex. « 380 V si P<0,75kW / 660 V si... » → recopie "
        f"TOUTE la liste de conditions) ;\n"
        f"   - un renvoi ou une délégation (ex. « As per vendor list », « See "
        f"Motor Data Sheet », « Refer to Note 46 », « As per specification ») → "
        f"recopie ce libellé tel quel comme valeur ;\n"
        f"   - une plage ou plusieurs colonnes (Normal/Design) → recopie-les "
        f"toutes.\n"
        f"   Ne considère un champ comme RÉELLEMENT ABSENT (valeur vide) QUE si "
        f"le texte contient un astérisque seul « * », « ** », « N/A », ou rien "
        f"du tout en face du libellé. Dans le doute, recopie ce que tu vois.\n"
        f"j) COMPOSANTS & MATÉRIAUX — n'en perds AUCUN. Pour la catégorie "
        f"Materiau : remplis chaque composant listé avec son matériau. Si le "
        f"document mentionne un composant AVEC un matériau qui ne correspond à "
        f"aucun champ listé (ex. « Bague d'usure : Stellite », « Diffuseur : "
        f"Duplex »), AJOUTE-le dans le champ 'Autres_composants' sous la forme "
        f"« Composant : matériau ; Composant2 : matériau2 ». Aucun couple "
        f"composant-matériau présent dans le document ne doit être omis.\n"
        f"k) LIS CHAQUE LIGNE. Le texte peut coller les mots sans espaces (ex. "
        f"« Brides refoulement : DN125mmPN10 », « Environnement : corrosif »). "
        f"Traite chaque ligne du document, n'en saute aucune, même si la mise "
        f"en forme est serrée.\n"
        f"l) RESTAURE LES ESPACES MANQUANTS. Le texte source provient d'un PDF "
        f"où des espaces ont été perdus, collant des mots entre eux (ex. "
        f"« U52 NouU45N » → « U52 N ou U45N » ; « Fonte à30% Cr+2,5% Mo » → "
        f"« Fonte à 30% Cr + 2,5% Mo » ; « 120à156 m3/h » → « 120 à 156 m3/h » ; "
        f"« 80dBà1m » → « 80 dB à 1 m »). Quand tu recopies une valeur, RÉTABLIS "
        f"les espaces naturels entre les mots, nombres et unités pour qu'elle "
        f"soit lisible. MAIS ne sépare JAMAIS les références/codes qui s'écrivent "
        f"collés (ex. « DN150 », « PN10 », « P2O5 », « RAL2003 », « AFM34 », "
        f"« U45N », « G6.3 » restent tels quels). En cas de doute, garde la "
        f"forme collée plutôt que de couper un code.\n\n"
        f"### FORMAT DE SORTIE (obligatoire)\n"
        f"Réponds UNIQUEMENT avec un objet JSON valide, sans texte avant/après, "
        f"respectant EXACTEMENT cette structure (mêmes clés) :\n"
        f"{json.dumps(skeleton, ensure_ascii=False)}"
    )


def build_material_prompt(tag: str, context: str) -> str:
    return (
        f"Voici la fiche technique d'une pompe (repère {tag}).\n\n"
        f"### TEXTE\n{context}\n\n"
        f"### TÂCHE UNIQUE\n"
        f"Liste TOUS les composants pour lesquels un MATÉRIAU est indiqué "
        f"dans le texte, SANS EXCEPTION. Inclus les composants standards "
        f"(corps, impulseur, arbre, chemise, etc.) ET tout autre composant "
        f"mentionné avec un matériau (bague d'usure, diffuseur, volute, "
        f"flasque, tirants, etc.). Restaure les espaces manquants dans les "
        f"matériaux (ex. « U52 NouU45N » → « U52 N ou U45N ») mais garde les "
        f"codes collés (U45N, AFM34...).\n"
        f"N'invente RIEN : uniquement ce qui est écrit avec son matériau.\n\n"
        f"### FORMAT\n"
        f"Réponds UNIQUEMENT en JSON : une liste d'objets "
        f'{{"composant": "...", "materiau": "...", "page": "NomFichier - Page X"}}. '
        f"Exemple : "
        f'{{"composants":[{{"composant":"Corps de la pompe","materiau":"Fonte","page":"x.pdf - Page 1"}}]}}'
    )